namespace NekoScriptGraph
{
    /// <summary>
    /// Версия ЯДРА — отдельно от версии плагина.
    ///
    /// Разделение намеренное. Ядро (папка Editor/Core/Esketamine) —
    /// самостоятельный слой: модель блоков, разбор, печать, диагностика,
    /// протокол MCP. Оно меняется редко. Плагин вокруг него — интерфейс,
    /// расширения, кошка, локали — выпускается чаще. Один общий номер
    /// заставлял бы поднимать версию ядра из-за правки в подписи кнопки, и
    /// наоборот: номер плагина рос бы от изменения в разборе.
    ///
    /// Правило: правишь что-то в Editor/Core/Esketamine — поднимай ЭТОТ номер.
    /// Правишь снаружи ядра — поднимай Nsg_Version.Plugin.
    ///
    /// Значение попадает в Nsg_Mcp.ServerVersion, то есть в отчёт
    /// initialize и в статусную страницу MCP-моста.
    /// </summary>
    public static class Nsg_Core
    {
        /// <summary>Имя слоя: используется в отчётах и в интерфейсе.</summary>
        public const string Name = "Esketamine";

        /// <summary>Версия ядра.</summary>
        public const string Version = "1.0.2";
    }
}
